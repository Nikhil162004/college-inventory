'use strict';
/**
 * Password storage using scrypt (memory-hard, built into Node.js).
 * Stored format:  scrypt$N$r$p$salt(base64)$hash(base64)
 * The cost parameters are stored with every hash so they can be raised later
 * without breaking existing accounts.
 */
const crypto = require('crypto');
const { promisify } = require('util');

const scrypt = promisify(crypto.scrypt);
const KEY_LENGTH = 64;
const MAX_MEM = 256 * 1024 * 1024;

// OWASP-recommended scrypt setting for passwords chosen by people.
let STRONG = { N: 1 << 15, r: 8, p: 3 };
// Used only for 12-character random temporary passwords generated by the server
// (about 59 bits of entropy, so they cannot be guessed even with a cheaper hash).
// The owner is forced to replace it at first sign-in, which then uses STRONG.
let LIGHT = { N: 1 << 12, r: 8, p: 1 };

/** Tests lower the cost so the suite runs quickly. Never call this in the app. */
function setCostForTests(params) {
  STRONG = params;
  LIGHT = params;
}

function derive(password, salt, { N, r, p }) {
  return scrypt(String(password).normalize('NFKC'), salt, KEY_LENGTH, { N, r, p, maxmem: MAX_MEM });
}

async function hashWith(password, params) {
  const salt = crypto.randomBytes(16);
  const key = await derive(password, salt, params);
  return ['scrypt', params.N, params.r, params.p, salt.toString('base64'), key.toString('base64')].join('$');
}

const hash = (password) => hashWith(password, STRONG);
const hashTemporary = (password) => hashWith(password, LIGHT);

async function verify(password, stored) {
  if (typeof password !== 'string' || typeof stored !== 'string') return false;
  const parts = stored.split('$');
  if (parts.length !== 6 || parts[0] !== 'scrypt') return false;
  const [N, r, p] = parts.slice(1, 4).map(Number);
  if (![N, r, p].every(Number.isInteger) || N < 2 || N > (1 << 20) || r < 1 || r > 32 || p < 1 || p > 16) return false;
  const salt = Buffer.from(parts[4], 'base64');
  const expected = Buffer.from(parts[5], 'base64');
  if (expected.length !== KEY_LENGTH) return false;
  const actual = await derive(password, salt, { N, r, p });
  return crypto.timingSafeEqual(actual, expected);
}

const TEMP_ALPHABET = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; // no 0/O, 1/I/L look-alikes
function generateTemporaryPassword() {
  let out = '';
  for (let i = 0; i < 12; i++) {
    if (i > 0 && i % 4 === 0) out += '-';
    out += TEMP_ALPHABET[crypto.randomInt(TEMP_ALPHABET.length)];
  }
  return out; // e.g. K7QM-2HXD-9TRB
}

const COMMON = new Set([
  'password12', 'password123', 'password1234', '1234567890', '12345678910', 'qwertyuiop',
  'qwerty12345', 'iloveyou123', 'admin12345', 'welcome123', 'welcome1234', 'india12345',
  'abcdefghij', 'abcd123456', '1q2w3e4r5t', 'letmein1234', 'college123', 'college1234',
  'student123', 'student1234', 'faculty123', 'changeme123', 'pass123456', '0123456789',
  '9876543210', '1111111111', '0000000000', 'qwerty123456', 'password@123', 'admin@1234',
]);

/** Returns an error message, or null when the password is acceptable. */
function policyError(password, user = {}) {
  if (typeof password !== 'string' || password.length < 10) return 'Use at least 10 characters.';
  if (password.length > 128) return 'Use at most 128 characters.';
  const lower = password.toLowerCase();
  if (COMMON.has(lower)) return 'That password is too common. Choose something harder to guess.';
  if (/^(.)\1+$/.test(password)) return 'Do not repeat a single character.';
  const id = String(user.college_id || '').toLowerCase();
  if (id.length >= 3 && lower.includes(id)) return 'Do not include your college ID in the password.';
  for (const part of String(user.name || '').toLowerCase().split(/\s+/)) {
    if (part.length >= 4 && lower.includes(part)) return 'Do not include your name in the password.';
  }
  return null;
}

module.exports = { hash, hashTemporary, verify, generateTemporaryPassword, policyError, setCostForTests };
